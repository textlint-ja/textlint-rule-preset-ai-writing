import TextLintTester from "textlint-tester";
import noAiEmptyPhrases from "../../src/rules/no-ai-empty-phrases";

const tester = new TextLintTester();

tester.run("no-ai-empty-phrases", noAiEmptyPhrases, {
    valid: [
        // 通常の文章
        "この関数は配列を受け取り、合計値を返します。",
        "設定ファイルにポート番号を記述します。",
        // 具体的に観点を示している文章
        "性能とセキュリティの2つの観点から比較します。",
        // 「結論を先に書く」のような良い実践は対象外
        "結論から言うと、この方法が最も速いです。",
        // 許可パターン（文字列）
        {
            text: "この章では設計を多角的に検討します。",
            options: {
                allows: ["多角的に"]
            }
        },
        // カテゴリ無効化
        {
            text: "いかがでしたか。",
            options: {
                disableConclusionPatterns: true
            }
        },
        {
            text: "この問題を深く掘り下げて解説します。",
            options: {
                disableFillerPatterns: true
            }
        },
        {
            text: "本記事では基礎を解説していきます。",
            options: {
                disableIntroductionPatterns: true
            }
        }
    ],
    invalid: [
        // 空虚な定型句（filler）
        {
            text: "この課題を多角的に検討します。",
            errors: [
                {
                    message:
                        "「多角的に」は具体性のない定型表現になりがちです。どの観点から述べるのかを具体的に書くことを検討してください。"
                }
            ]
        },
        {
            text: "この問題を深く掘り下げて解説します。",
            errors: [
                {
                    message:
                        "「掘り下げる」は内容を説明しない空虚な動詞になりがちです。何をどこまで説明するのかを具体的に書くことを検討してください。"
                }
            ]
        },
        {
            text: "この分野は奥が深いです。",
            errors: [
                {
                    message:
                        "「奥が深い」は内容のない感想になりがちです。具体的にどの点が複雑なのかを書くことを検討してください。"
                }
            ]
        },
        {
            text: "この課題に正面から向き合います。",
            errors: [
                {
                    message:
                        "「正面から扱う／向き合う」は中身のない型になりがちです。具体的に何をするのかを書くことを検討してください。"
                }
            ]
        },
        // 機械的な結論段落（conclusion）
        {
            text: "いかがでしたか。",
            errors: [
                {
                    message:
                        "「いかがでしたか」は内容のない定型的な結びです。本文で述べた要点をまとめることを検討してください。"
                }
            ]
        },
        {
            text: "ぜひ試してみてください。",
            errors: [
                {
                    message:
                        "「ぜひ〜してみてください」は定型的な締めの表現になりがちです。読み手が次に取れる具体的な行動を示すことを検討してください。"
                }
            ]
        },
        {
            text: "参考になれば幸いです。",
            errors: [
                {
                    message: "「参考になれば幸いです」は定型的な結びです。本文の要点を述べることを検討してください。"
                }
            ]
        },
        {
            text: "最後までお読みいただきありがとうございました。",
            errors: [
                {
                    message:
                        "「最後までお読みいただき」は定型的な挨拶です。技術的な内容に集中することを検討してください。"
                }
            ]
        },
        // 過剰な前置き構造（introduction）
        {
            text: "本記事では基礎を解説していきます。",
            errors: [
                {
                    message:
                        "「本記事では〜を解説していきます」は冗長な前置きになりがちです。前置きを省いて本題から書き始めることを検討してください。"
                }
            ]
        },
        {
            text: "仕組みについて詳しく見ていきましょう。",
            errors: [
                {
                    message:
                        "「〜を詳しく見ていきましょう」は内容のない案内文になりがちです。前置きを省いて本題に入ることを検討してください。"
                }
            ]
        }
    ]
});
